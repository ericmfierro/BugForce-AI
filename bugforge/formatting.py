"""Render validated bug reports to Markdown."""
from .models import BugReport


def format_report(report: BugReport, project: str, environment: str) -> str:
    steps = '\n'.join(f'{i}. {item}' for i, item in enumerate(report.steps_to_reproduce, 1))
    tests = '\n'.join(f'- {item}' for item in report.suggested_tests)
    questions = '\n'.join(f'- {item}' for item in report.follow_up_questions) or '- None provided'
    tags = ', '.join(report.tags) or 'None'
    return (f'# {report.title}\n\n'
            f'**Project:** {project}\n\n'
            f'**Environment:** {environment}\n\n'
            f'**Severity:** {report.severity} — {report.severity_reason}\n\n'
            f'**Category:** {report.category}\n\n'
            f'**Tags:** {tags}\n\n'
            f'## Summary\n{report.summary}\n\n'
            f'## Suggested steps to reproduce (verify in-game)\n{steps}\n\n'
            f'## Expected behavior\n{report.expected_behavior}\n\n'
            f'## Actual behavior\n{report.actual_behavior}\n\n'
            f'## Possible cause (hypothesis)\n{report.possible_cause}\n\n'
            f'## Suggested tests\n{tests}\n\n'
            f'## Follow-up questions\n{questions}\n\n'
            '---\nGenerated by BugForge AI. AI suggestions are not verified test results.\n')
